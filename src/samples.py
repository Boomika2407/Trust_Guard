def sample_batch_csv() -> bytes:
    """A 2-row CSV in the Kaggle layout, handy for trying the batch tab."""
    rows = []
    for sample in (LEGIT_SAMPLE, FRAUD_SAMPLE):
        rows.append({"Time": sample["time"],
                     **{f"V{i + 1}": v for i, v in enumerate(sample["v"])},
                     "Amount": sample["amount"]})
    buf = io.StringIO()
    pd.DataFrame(rows).to_csv(buf, index=False)
    return buf.getvalue().encode("utf-8")
